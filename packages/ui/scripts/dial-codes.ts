/**
 * Dial codes (DESIGN.md §6.1, §9.59): writes src/flags/finDialCodes.ts, each country's calling code from the
 * open-source `libphonenumber-js` (Google's libphonenumber metadata, MIT; version pinned in package.json), for the
 * countries in src/flags/finFlags.ts. Countries without a calling code (Antarctica, Bouvet Island…) are left out.
 * The file is committed, so the library is only a dev dependency; a test fails if it no longer matches the library.
 *
 * Run: node scripts/dial-codes.ts (after updating libphonenumber-js or the flags).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getCountries, getCountryCallingCode, type CountryCode } from 'libphonenumber-js';
import { finFlags } from '../src/flags/finFlags.ts';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '../src/flags/finDialCodes.ts');

const library = new Set<string>(getCountries());
const entries = Object.keys(finFlags)
  .filter((code) => library.has(code))
  .map((code) => `  ${code}: '+${getCountryCallingCode(code as CountryCode)}',`);

writeFileSync(
  OUT,
  `/**
 * Each country's dialling code (DESIGN.md §9.59), from the open-source \`libphonenumber-js\` (MIT; version pinned in
 * package.json). Generated by \`node scripts/dial-codes.ts\`; don't edit by hand. Countries without a calling code
 * (Antarctica, Bouvet Island…) aren't listed.
 */
import type { FinFlagCountry } from './finFlags';

export const finDialCodes: Partial<Record<FinFlagCountry, string>> = {
${entries.join('\n')}
};
`,
);

console.log(`dial codes: ${entries.length} countries (libphonenumber-js, MIT)`);
