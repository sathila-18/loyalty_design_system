/**
 * Tailwind theme (DESIGN.md §3.11): writes src/styles/theme.css from the token files, so the utilities can only ever
 * be our tokens. Every value is `var(--fin-*)` (`@theme inline`), so brand and theme still switch at runtime through
 * data-brand / data-theme; `reference` keeps Tailwind from writing variables of its own (with the `fin` prefix they
 * would be named --fin-* and clash with the tokens).
 *
 * Reads: @finspace-loyalty/tokens dist/tokens.css (semantic colours, space, size, radius, text styles),
 * src/styles.css (shadows) and dist/breakpoints.ts. Tailwind's own defaults (palette, spacing scale, radius, text
 * sizes, shadows, breakpoints…) are all removed first.
 *
 * Run: node scripts/tailwind-theme.ts (part of `pnpm icons`). `--check` fails if theme.css is out of date
 * (test/tailwind-theme.test.ts runs it), so a token export can't leave the theme behind.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = dirname(require.resolve('@finspace-loyalty/tokens/tokens.css'));
const OUT = join(here, '../src/styles/theme.css');

const tokensCss = readFileSync(join(TOKENS, 'tokens.css'), 'utf8');
const stylesCss = readFileSync(join(TOKENS, '../src/styles.css'), 'utf8');
const breakpointsTs = readFileSync(join(TOKENS, 'breakpoints.ts'), 'utf8');

/** Every variable name declared in a CSS text, in order, once. */
const declared = (css: string) => [...new Set([...css.matchAll(/^\s*(--fin-[a-z0-9-]+):/gm)].map((m) => m[1]!))];
const names = declared(tokensCss);
const suffixes = (group: string) => names.filter((n) => n.startsWith(`--fin-${group}-`)).map((n) => n.slice(`--fin-${group}-`.length));

const bg = suffixes('bg');
const text = suffixes('text');
const border = suffixes('border');
const fg = suffixes('fg');
const alpha = suffixes('alpha');
const space = suffixes('space');
const size = suffixes('size');
const radius = suffixes('radius');
// Text styles: the shorthand (--fin-font-body-medium), not its parts (-size, -weight, -line-height, -family).
const fonts = suffixes('font').filter((s) => !/-(size|weight|line-height|family|letter-spacing)$/.test(s));
const shadows = declared(stylesCss).filter((n) => n.startsWith('--fin-shadow-')).map((n) => n.slice('--fin-shadow-'.length));
const breakpoints = [...breakpointsTs.matchAll(/^\s+(\w+): '(\([^']+\))',$/gm)].map((m) => [m[1]!, m[2]!] as const);

for (const [what, list] of Object.entries({ bg, text, border, fg, alpha, space, size, radius, fonts, shadows, breakpoints })) {
  if (list.length === 0) {
    console.error(`tailwind-theme: no ${what} tokens found; has the token build changed?`);
    process.exit(1);
  }
}

const lines = (namespace: string, list: string[], token: (s: string) => string, key = (s: string) => s) =>
  list.map((s) => `  --${namespace}-${key(s)}: var(${token(s)});`).join('\n');
const group = (g: string) => (s: string) => `--fin-${g}-${s}`;
const prefixed = (p: string) => (s: string) => `${p}-${s}`;

const sizeNamespaces = ['width', 'height', 'size', 'min-width', 'max-width', 'min-height', 'max-height', 'flex-basis'];
// The ring utilities draw Figma's inside strokes (box-shadow: inset 0 0 0 <w> <border token>).
const borderColourNamespaces = ['border-color', 'outline-color', 'ring-color', 'inset-ring-color'];

const css = `/*
 * GENERATED by packages/ui/scripts/tailwind-theme.ts from @finspace-loyalty/tokens. Do not edit by hand:
 * re-export the tokens and run \`pnpm icons\` (DESIGN.md §3.11).
 *
 * The Tailwind theme: only our tokens, no Tailwind defaults. Every utility reads var(--fin-*) where it's used,
 * so data-brand and data-theme keep switching at runtime. The library compiles it with the \`fin\` prefix
 * (fin:bg-primary); an app on Tailwind 4 may import it too, to use the same utilities on its pages (optional).
 *
 *   bg-*        background, from --fin-bg-*      (cross-group, as Figma: bg-fg-*, bg-border-*, bg-alpha-*)
 *   text-*      text colour, from --fin-text-*
 *   fg-*        icon colour (color), from --fin-fg-*
 *   border-* outline-* ring-* inset-ring-*      from --fin-border-*   (cross-group: border-fg-*, border-bg-*, ring-fg-*…)
 *   fill-* stroke-* caret-*                     with the group named: stroke-fg-*, caret-fg-*, fill-bg-*
 *   p-* m-* gap-* inset-* translate-*          space names: xxs xs s m l xl 2xl … 12xl none
 *   w-* h-* size-* min-* max-* basis-*         size numbers: 0 2 4 6 8 12 … 343 (the --fin-size-* tokens)
 *   rounded-*   radius: none xs s m l xl full
 *   shadow-*    resting-cards panel-sheets sticky menu sticky-start sticky-end
 *   font-*      text styles (the font shorthand): font-body-medium, font-button-large…
 *   bp-md: bp-lg: bp-xl: bp-xxl:               breakpoint variants (min-width)
 */

@theme {
  --*: initial;
}

@theme inline reference {
  /* Background */
${lines('background-color', bg, group('bg'))}
${lines('background-color', fg, group('fg'), prefixed('fg'))}
${lines('background-color', border, group('border'), prefixed('border'))}
${lines('background-color', alpha, group('alpha'), prefixed('alpha'))}

  /* Text */
${lines('text-color', text, group('text'))}

  /* Icon colour (the fg-* utility below) */
${lines('fg', fg, group('fg'))}

  /* Borders, outlines, rings */
${borderColourNamespaces.map((ns) => lines(ns, border, group('border'))).join('\n')}
${lines('border-color', fg, group('fg'), prefixed('fg'))}
${lines('border-color', bg, group('bg'), prefixed('bg'))}
${lines('border-color', alpha, group('alpha'), prefixed('alpha'))}
${['ring-color', 'inset-ring-color'].map((ns) => [lines(ns, fg, group('fg'), prefixed('fg')), lines(ns, bg, group('bg'), prefixed('bg'))].join('\n')).join('\n')}

  /* SVG and caret */
${['fill', 'stroke'].map((ns) => [lines(ns, fg, group('fg'), prefixed('fg')), lines(ns, bg, group('bg'), prefixed('bg')), lines(ns, border, group('border'), prefixed('border'))].join('\n')).join('\n')}
${lines('caret-color', fg, group('fg'), prefixed('fg'))}

  /* Spacing (padding, margin, gap, inset, translate) */
${lines('spacing', space, group('space'))}

  /* Sizes */
${sizeNamespaces.map((ns) => lines(ns, size, group('size'))).join('\n')}

  /* Radius */
${lines('radius', radius, group('radius'))}

  /* Shadows (hand-written foundation styles, DESIGN.md §4.2) */
${lines('shadow', shadows, group('shadow'))}
}

/* Icon colour: FinIcon has no colour of its own and inherits this. */
@utility fg-* {
  color: --value(--fg-*);
}

/* Text styles: the whole font shorthand, never its parts (the family changes with the brand). */
${fonts.map((f) => `@utility font-${f} {\n  font: var(--fin-font-${f});\n}`).join('\n\n')}

/*
 * Brand and theme come from the tokens (data-brand, data-theme), never from Tailwind's dark: variant: it would follow
 * the OS setting, not the app's theme. Redefined so it never matches (the lint bans it too).
 */
@custom-variant dark (&:not(&));

/* Breakpoints (DESIGN.md §3.7), from @finspace-loyalty/tokens/breakpoints. */
${breakpoints.map(([k, q]) => `@custom-variant bp-${k} (@media ${q});`).join('\n')}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // Missing counts as out of date.
  }
  if (current !== css) {
    console.error('tailwind-theme: src/styles/theme.css is out of date with the tokens. Run `pnpm icons`.');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, css);
}
